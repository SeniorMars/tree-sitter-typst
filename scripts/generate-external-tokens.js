#!/usr/bin/env node
import {readFileSync, writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";

import {EXTERNAL_TOKENS} from "../grammar/externals.js";

const output = fileURLToPath(
  new URL("../src/external_tokens.h", import.meta.url),
);
const check = process.argv.includes("--check");

const cNames = new Set();
const grammarNames = new Set();
for (const [cName, grammarName] of EXTERNAL_TOKENS) {
  if (!/^[A-Z][A-Z0-9_]*$/.test(cName)) {
    throw new Error(`invalid C external-token name: ${cName}`);
  }
  if (!/^_?[a-z][a-z0-9_]*$/.test(grammarName)) {
    throw new Error(`invalid grammar external-token name: ${grammarName}`);
  }
  if (cNames.has(cName) || grammarNames.has(grammarName)) {
    throw new Error(`duplicate external token: ${cName}/${grammarName}`);
  }
  cNames.add(cName);
  grammarNames.add(grammarName);
}

const body = EXTERNAL_TOKENS
  .map(([cName]) => `  ${cName},`)
  .join("\n");
const text = `// Generated by scripts/generate-external-tokens.js. Do not edit.
#ifndef TREE_SITTER_TYPST_EXTERNAL_TOKENS_H_
#define TREE_SITTER_TYPST_EXTERNAL_TOKENS_H_

enum TokenType {
${body}
};

#endif
`;

if (check) {
  if (readFileSync(output, "utf8") !== text) {
    throw new Error(
      "src/external_tokens.h is stale; run npm run generate:externals",
    );
  }
  console.log(`external-token manifest matches ${EXTERNAL_TOKENS.length} tokens`);
} else {
  writeFileSync(output, text);
  console.log(`wrote ${output} (${EXTERNAL_TOKENS.length} tokens)`);
}
